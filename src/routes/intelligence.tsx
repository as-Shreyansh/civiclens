import { createFileRoute, Link } from "@tanstack/react-router";
import { useState } from "react";
import { Pause, Play, Zap } from "lucide-react";
import { Button } from "@/components/ui/button";
import { OpsShell } from "@/components/civic/Shells";
import { LoadingGrid, Panel, SimLabel, Empty } from "@/components/civic/ui";
import { setSimRunning, simulateOne, useDB } from "@/lib/store";
import { THRESHOLDS } from "@/lib/anomaly";

export const Route = createFileRoute("/intelligence")({
  head: () => ({
    meta: [
      { title: "Defect intelligence — CIVICLENS" },
      { name: "description", content: "Rule-based anomaly detection on simulated vehicle sensor readings." },
      { property: "og:title", content: "Defect intelligence — CIVICLENS" },
      { property: "og:description", content: "Explainable, rule-based road anomaly detection." },
    ],
  }),
  component: Intel,
});

function Intel() {
  const db = useDB();
  const [only, setOnly] = useState(false);
  const [page, setPage] = useState(0);
  if (!db) return <OpsShell title="Defect intelligence" crumb="Intelligence"><LoadingGrid /></OpsShell>;
  const evs = db.events.filter((e) => !only || e.flagged);
  const per = 15, pages = Math.max(1, Math.ceil(evs.length / per));
  const shown = evs.slice(page * per, page * per + per);
  return (
    <OpsShell title="Defect intelligence" crumb="Intelligence" actions={<Button size="sm" variant="outline" onClick={() => setSimRunning(!db.simRunning)}>{db.simRunning ? <Pause className="size-4" /> : <Play className="size-4" />}<span className="hidden sm:inline">{db.simRunning ? "Pause feed" : "Resume feed"}</span></Button>}>
      <Panel title={<span className="flex items-center gap-2">Rule-based anomaly detection <SimLabel /></span>}>
        <div className="grid gap-3 text-sm md:grid-cols-3">
          <div className="rounded-lg bg-muted p-3"><b>Vibration ≥ {THRESHOLDS.vibration}g</b><br /><span className="text-muted-foreground">flags a potential anomaly</span></div>
          <div className="rounded-lg bg-muted p-3"><b>Surface score ≥ {THRESHOLDS.surface}</b><br /><span className="text-muted-foreground">flags a potential anomaly</span></div>
          <div className="rounded-lg bg-muted p-3"><b>High vibration at ≥ {THRESHOLDS.highSpeed} km/h</b><br /><span className="text-muted-foreground">raises inspection urgency</span></div>
        </div>
        <p className="mt-3 text-xs text-muted-foreground">These are fixed threshold rules, not a trained AI model. Readings are generated by a simulator, not physical sensors. Severity 3+ events create or link a defect; events within 60 m and 30 min of an open defect are linked instead of duplicated.</p>
      </Panel>
      <Panel title="Sensor events" action={
        <div className="flex items-center gap-2">
          <label className="flex items-center gap-1.5 text-sm"><input type="checkbox" checked={only} onChange={(e) => { setOnly(e.target.checked); setPage(0); }} /> Flagged only</label>
          <Button size="sm" onClick={() => simulateOne()}><Zap className="size-4" /> Generate one</Button>
        </div>
      }>
        {shown.length === 0 ? <Empty>No events.</Empty> : (
          <div className="overflow-x-auto">
            <table className="w-full text-sm">
              <thead className="text-left text-xs uppercase text-muted-foreground"><tr><th className="p-2">Time</th><th className="p-2">Location</th><th className="p-2 text-right">Vib (g)</th><th className="p-2 text-right">Speed</th><th className="p-2 text-right">Surface</th><th className="p-2">Decision</th><th className="p-2">Sev</th><th className="p-2">Action</th><th className="p-2">Defect</th></tr></thead>
              <tbody className="divide-y">
                {shown.map((e) => (
                  <tr key={e.id} className={e.flagged ? "bg-high/5" : ""}>
                    <td className="whitespace-nowrap p-2 font-mono text-xs">{new Date(e.ts).toLocaleString()}</td>
                    <td className="p-2">{e.location}<div className="font-mono text-[10px] text-muted-foreground">{e.lat}, {e.lng}</div></td>
                    <td className={`p-2 text-right font-mono ${e.vibration >= THRESHOLDS.vibration ? "text-high" : ""}`}>{e.vibration}</td>
                    <td className="p-2 text-right font-mono">{e.speed}</td>
                    <td className={`p-2 text-right font-mono ${e.surface >= THRESHOLDS.surface ? "text-high" : ""}`}>{e.surface}</td>
                    <td className="p-2"><span className={e.flagged ? "font-semibold text-high" : "text-muted-foreground"}>{e.flagged ? "Flagged" : "Normal"}</span><div className="text-xs text-muted-foreground">{e.reasons.join("; ")}</div></td>
                    <td className="p-2 font-mono">{e.severity || "—"}</td>
                    <td className="p-2 text-xs">{e.action}</td>
                    <td className="p-2">{e.defectId && db.defects.some((d) => d.id === e.defectId) ? <Link to="/defects/$id" params={{ id: e.defectId }} className="font-mono text-xs text-cyan hover:underline">{e.defectId}</Link> : "—"}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
        <div className="mt-3 flex items-center justify-end gap-2 text-sm">
          <Button size="sm" variant="outline" disabled={page === 0} onClick={() => setPage(page - 1)}>Prev</Button>
          <span>{page + 1} / {pages}</span>
          <Button size="sm" variant="outline" disabled={page >= pages - 1} onClick={() => setPage(page + 1)}>Next</Button>
        </div>
      </Panel>
    </OpsShell>
  );
}
